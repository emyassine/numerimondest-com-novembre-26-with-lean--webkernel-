namespace Webkernel\Exporters\Xlsx\Writer\Common\Manager;

use Webkernel\Exporters\Xlsx\Common\Entity\Row;
use Webkernel\Exporters\Xlsx\Common\Exception\InvalidArgumentException;
use Webkernel\Exporters\Xlsx\Common\Exception\IOException;
use Webkernel\Exporters\Xlsx\Writer\Common\Entity\Worksheet;

/**
 * @internal
 */
interface WorksheetManagerInterface
{
    /**
     * Adds a row to the worksheet.
     *
     * @param Worksheet $worksheet The worksheet to add the row to
     * @param Row       $row       The row to be added
     *
     * @throws IOException              If the data cannot be written
     * @throws InvalidArgumentException If a cell value's type is not supported
     */
    public function addRow(Worksheet $worksheet, Row $row): void;

    /**
     * Prepares the worksheet to accept data.
     *
     * @param Worksheet $worksheet The worksheet to start
     *
     * @throws IOException If the sheet data file cannot be opened for writing
     */
    public function startSheet(Worksheet $worksheet): void;

    /**
     * Closes the worksheet.
     */
    public function close(Worksheet $worksheet): void;
}
