namespace Webkernel\Markdown\Extension\CommonMark\Renderer\Block;

use \Webkernel\Markdown\Extension\CommonMark\Node\Block\ListItem;
use \Webkernel\Markdown\Node\Block\AbstractBlock;
use \Webkernel\Markdown\Node\Block\Paragraph;
use \Webkernel\Markdown\Node\Block\TightBlockInterface;
use \Webkernel\Markdown\Node\Node;
use \Webkernel\Markdown\Renderer\ChildNodeRendererInterface;
use \Webkernel\Markdown\Renderer\NodeRendererInterface;
use \Webkernel\Markdown\Util\HtmlElement;
use \Webkernel\Markdown\Xml\XmlNodeRendererInterface;

final class ListItemRenderer implements NodeRendererInterface, XmlNodeRendererInterface
{
    /**
     * @param ListItem $node
     *
     * {@inheritDoc}
     *
     * @psalm-suppress MoreSpecificImplementedParamType
     */
    public function render(Node $node, ChildNodeRendererInterface $childRenderer): \Stringable
    {
        ListItem::assertInstanceOf($node);

        $contents = $childRenderer->renderNodes($node->children());

        $inTightList = ($parent = $node->parent()) && $parent instanceof TightBlockInterface && $parent->isTight();

        if ($this->needsBlockSeparator($node->firstChild(), $inTightList)) {
            $contents = "\n" . $contents;
        }

        if ($this->needsBlockSeparator($node->lastChild(), $inTightList)) {
            $contents .= "\n";
        }

        $attrs = $node->data->get('attributes');

        return new HtmlElement('li', $attrs, $contents);
    }

    public function getXmlTagName(Node $node): string
    {
        return 'item';
    }

    /**
     * {@inheritDoc}
     */
    public function getXmlAttributes(Node $node): array
    {
        return [];
    }

    private function needsBlockSeparator(?Node $child, bool $inTightList): bool
    {
        if ($child instanceof Paragraph && $inTightList) {
            return false;
        }

        return $child instanceof AbstractBlock;
    }
}
