namespace Webkernel\Markdown\Extension\DisallowedRawHtml;

use \Webkernel\Markdown\Environment\EnvironmentBuilderInterface;
use \Webkernel\Markdown\Extension\CommonMark\Node\Block\HtmlBlock;
use \Webkernel\Markdown\Extension\CommonMark\Node\Inline\HtmlInline;
use \Webkernel\Markdown\Extension\CommonMark\Renderer\Block\HtmlBlockRenderer;
use \Webkernel\Markdown\Extension\CommonMark\Renderer\Inline\HtmlInlineRenderer;
use \Webkernel\Markdown\Extension\ConfigurableExtensionInterface;
use \Webkernel\Markdown\Configuration\ConfigurationBuilderInterface;
use \Webkernel\Markdown\Configuration\Schema\Expect;

final class DisallowedRawHtmlExtension implements ConfigurableExtensionInterface
{
    private const DEFAULT_DISALLOWED_TAGS = [
        'title',
        'textarea',
        'style',
        'xmp',
        'iframe',
        'noembed',
        'noframes',
        'script',
        'plaintext',
    ];

    public function configureSchema(ConfigurationBuilderInterface $builder): void
    {
        $builder->addSchema('disallowed_raw_html', Expect::structure([
            'disallowed_tags' => Expect::listOf('string')->default(self::DEFAULT_DISALLOWED_TAGS)->mergeDefaults(false),
        ]));
    }

    public function register(EnvironmentBuilderInterface $environment): void
    {
        $environment->addRenderer(HtmlBlock::class, new DisallowedRawHtmlRenderer(new HtmlBlockRenderer()), 50);
        $environment->addRenderer(HtmlInline::class, new DisallowedRawHtmlRenderer(new HtmlInlineRenderer()), 50);
    }
}
