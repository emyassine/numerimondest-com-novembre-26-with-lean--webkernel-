namespace Webkernel\View;

use Webkernel\View\Contracts\View as ViewContract;

/** Renderable result for a named view and its input data. */
final class ViewResult implements Htmlable, ViewContract, \Stringable
{
    /** @var array<string, \Closure> */
    private static array $macros = [];

    private array $data;

    /** Optional package-owned render configuration (for example Livewire page layouts). */
    public mixed $layoutConfig = null;

    /**
     * @param $name string Resolved view name.
     * @param $data array<string, mixed> Variables exposed to the template.
     * @param $inline_html string|null Trusted inline HTML generated by Webkernel.
     */
    public function __construct(
        private readonly string $name,
        array $data,
        private ?string $inline_html = null,
    ) {
        $this->data = $data;
    }

    /** Adds variables for this render. */
    public function with(string|array $key, mixed $value = null): self
    {
        $this->data = is_array($key)
            ? array_merge($this->data, $key)
            : array_merge($this->data, [$key => $value]);

        return $this;
    }

    /** @param $data array<string, mixed> */
    public function withData(array $data): self
    {
        return $this->with($data);
    }

    /** Register a chainable extension method without adding a framework facade. */
    public static function macro(string $name, callable $macro): void
    {
        self::$macros[$name] = $macro instanceof \Closure ? $macro : \Closure::fromCallable($macro);
    }

    public static function mixin(object $mixin, bool $replace = true): void
    {
        $reflection = new \ReflectionClass($mixin);
        foreach ($reflection->getMethods(\ReflectionMethod::IS_PUBLIC) as $method) {
            if (! $replace && self::hasMacro($method->name)) { continue; }
            $method->setAccessible(true);
            self::macro($method->name, $method->invoke($mixin));
        }
    }

    public static function hasMacro(string $name): bool
    {
        return isset(self::$macros[$name]);
    }

    public static function flushMacros(): void
    {
        self::$macros = [];
    }

    public function __call(string $name, array $arguments): mixed
    {
        $macro = self::$macros[$name] ?? null;
        if ($macro === null) {
            throw new \BadMethodCallException('Undefined view-result macro ['.$name.'].');
        }

        return $macro->call($this, ...$arguments);
    }

    /** Configure a package page layout through the registered view-result macro. */
    public function layout(string $name, array $data = []): mixed
    {
        return $this->__call('layout', [$name, $data]);
    }

    /** Wrap this result in a layout view and expose its rendered content as `slot`. */
    public function wrapInLayout(string $name, array $data = []): self
    {
        return View::make($name, $data + ['slot' => $this]);
    }

    /** @return array<string, mixed> */
    public function getData(): array
    {
        return $this->data;
    }

    public function getName(): string
    {
        return $this->name;
    }

    /** Laravel view-contract spelling retained for component interoperability. */
    public function name(): string
    {
        return $this->name;
    }

    /** Renders the view into an HTML string. */
    public function render(): string
    {
        View::compose($this);
        if ($this->inline_html !== null) {
            return $this->inline_html;
        }

        $engine = View::engine();
        return $engine->isRendering() ? $engine->html($this->name, $this->data) : $engine->run($this->name, $this->data);
    }

    public function __toString(): string
    {
        return $this->render();
    }

    public function to_html(): string
    {
        return $this->render();
    }

    public function toHtml(): string
    {
        return $this->render();
    }
}
