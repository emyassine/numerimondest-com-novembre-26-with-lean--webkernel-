namespace Webkernel\Utilities\Inflection\Rules\NorwegianBokmal;

use \Webkernel\Utilities\Inflection\Rules\Patterns;
use \Webkernel\Utilities\Inflection\Rules\Ruleset;
use \Webkernel\Utilities\Inflection\Rules\Substitutions;
use \Webkernel\Utilities\Inflection\Rules\Transformations;

final class Rules
{
    public static function getSingularRuleset(): Ruleset
    {
        return new Ruleset(
            new Transformations(...Inflectible::getSingular()),
            new Patterns(...Uninflected::getSingular()),
            (new Substitutions(...Inflectible::getIrregular()))->getFlippedSubstitutions()
        );
    }

    public static function getPluralRuleset(): Ruleset
    {
        return new Ruleset(
            new Transformations(...Inflectible::getPlural()),
            new Patterns(...Uninflected::getPlural()),
            new Substitutions(...Inflectible::getIrregular())
        );
    }
}
